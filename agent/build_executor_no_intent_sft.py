"""Synthesize executor SFT rows with no intent/template in the model input.

Purpose: ablation training for validating whether explicit intent and answer
template fields are useful. The new rows use only:

- user question
- external reference information

as the user-side input. By default the assistant target is regenerated by the
teacher API under the same no-intent/no-template prompt. A legacy ``copy`` mode
is kept for debugging.

The output schema matches ``agent.merge_final_sft`` executor input, so it can be
merged into final prompt JSONL directly:

    python -m agent.build_executor_no_intent_sft \
    --input agent/outputs/health/valid_executor_answer_sft.jsonl \
    --output agent/outputs/health/valid_executor_no_intent_sft.jsonl

    python -m agent.merge_final_sft \
    --planner-final agent/outputs/health/valid_planner_final_prompt.jsonl \
    --executor-input agent/outputs/health/valid_executor_no_intent_sft.jsonl \
    --output agent/outputs/health/valid_no_intent_merged_sft.jsonl
"""

