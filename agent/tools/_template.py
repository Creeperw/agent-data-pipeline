"""【工具模板】复制本文件为 ``agent/tools/<工具名>.py`` 再改。

===============================================================================
改哪几处
===============================================================================

1. ``SPEC["function"]["name"]`` 必须改成**文件名**（不含 ``.py``），两者不一致
   会被保存校验拦下 —— 否则模型调用的名字和实际加载的文件对不上。
2. ``SPEC["function"]["description"]`` 是模型唯一的判断依据。写「什么时候该用它」
   比写「它做什么」更重要，模型是靠这句话决定要不要调用的。
3. ``parameters`` 按需增删。``required`` 里没列的字段模型可以省略，``run()`` 里
   要自己兜底。
4. ``run()`` 可选，见下方第 3 节。
5. 在项目的 ``tools.json`` 里启用：``{"enabled": ["<工具名>"]}``。
   文件不存在等价于「一个都没开」，所以老项目不受影响。

===============================================================================
三条硬约束
===============================================================================

* **SPEC 必须是纯字面量 dict。** 加载器和控制台都用 ``ast`` 读源码文本取 SPEC，
  不执行本文件。写成函数调用或变量拼接会读不到。
* **模块顶层不要 import ``agent.core`` 或任何重依赖**（torch / transformers /
  openai …）。加载工具时领域正在加载中，顶层导入会形成加载期循环依赖，也会让
  控制台的「工具库」页面变慢。需要时在 ``run()`` 里延迟导入。
* **``from agent.tools import FatalToolError`` 只能写在 ``run()`` 里**，同理。

===============================================================================
1. 环境变量（凭据一律走这里）
===============================================================================

凭据统一放 ``agent/.env``，代码里只出现**变量名**。控制台「齿轮 → 运行时配置」
可填，也可以直接在 ``agent/.env`` 里写一行 ``KEY=值``。

不要把 key 写进这个文件当常量。写进代码的 key 会跟着仓库一起提交出去，而且换
key 得改代码、重启服务；放 ``.env`` 只需改配置，``.env`` 已在 .gitignore 里。

命名约定 ``<服务名>_API_KEY``，全大写。用到就把下面那行的注释去掉。

===============================================================================
2. 两种失败语义，别选错
===============================================================================

* **软失败** —— 参数不合法、缺必填项。返回一句 ``"…失败：原因"`` 文本即可。这条
  会被当成一次正常的工具观测写进训练样本（工具失败本身也是一种观测，模型该学会
  应对）。
* **硬失败** —— 欠费 / 断网 / key 失效。这类问题继续跑只会白烧教师模型额度，要抛
  ``FatalToolError`` 让整条流水线停下来（``generator`` 会取消其余任务并以
  ``SystemExit(2)`` 结束，已写入的样本仍可断点续跑）。

===============================================================================
3. run() 是可选的
===============================================================================

不写 ``run()`` 时工具返回 ``MOCK_RESPONSE``，其中 ``{参数名}`` 会被实际调用参数
替换，认不出的占位符原样保留。可以先用 mock 把 schema 和调用时机跑通，再补实现。

写了 ``run()`` 就走真实执行，``MOCK_RESPONSE`` 不再生效。签名支持两种：

    def run(arguments, sample=None)      # 需要读到当前样本时用这种
    def run(arguments)                   # 只依赖入参时用这种

``sample`` 是当前这条 seed（``search_rag`` 用它取预置的 ``rag_summary``）。返回值
转成字符串后作为工具观测；返回带 ``content`` 属性的对象也可以。

本文件下面给出的是一个**带 mock 的完整例子**，直接复制可用。
"""

