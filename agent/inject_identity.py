def parse_json(text: str) -> dict[str, Any] | None:
    if not text:
        return None
    text = text.strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass
    fenced = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, flags=re.S)
    if fenced:
        try:
            return json.loads(fenced.group(1))
        except json.JSONDecodeError:
            pass
    start = text.find("{")
    end = text.rfind("}")
    if start >= 0 and end > start:
        try:
            return json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            return None
    return None


def validate_executor_sample(parsed: Any, name: str, team: str) -> tuple[bool, str]:
    if not isinstance(parsed, dict):
        return False, "not_dict"
    user_query = str(parsed.get("user_query") or "").strip()
    answer = str(parsed.get("answer") or "").strip()
    reasoning = str(parsed.get("reasoning") or "").strip()
    if not user_query or not answer or not reasoning:
        return False, "empty_field"
    if len(user_query) < 4 or len(user_query) > 200:
        return False, f"user_query_length={len(user_query)}"
    if len(answer) < 100 or len(answer) > 1200:
        return False, f"answer_length={len(answer)}"
    if name not in answer and name.replace(" ", "") not in answer:
        return False, "missing_name"
    if team not in answer and team.replace(" ", "") not in answer:
        return False, "missing_team"
    forbidden = (
        "作为 AI 模型",
        "作为AI模型",
        "I am ChatGPT",
        "I am Qwen",
        "我是 ChatGPT",
        "我是Qwen",
        "我是 Qwen",
    )
    if any(token in answer for token in forbidden):
        return False, "forbidden_phrase"
    return True, ""


def validate_planner_sample(parsed: Any) -> tuple[bool, str]:
    if not isinstance(parsed, dict):
        return False, "not_dict"
    user_query = str(parsed.get("user_query") or "").strip()
    reasoning = str(parsed.get("reasoning") or "").strip()
    if not user_query or not reasoning:
        return False, "empty_field"
    if len(user_query) < 4 or len(user_query) > 200:
        return False, f"user_query_length={len(user_query)}"
    if len(reasoning) < 30 or len(reasoning) > 400:
        return False, f"reasoning_length={len(reasoning)}"
    if "planning_finish" not in reasoning and "结束规划" not in reasoning:
        return False, "reasoning_missing_finish_signal"
    return True, ""


def existing_ids(path: Path) -> set[str]:
    ids: set[str] = set()
    if not path.exists():
        return ids
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            row_id = row.get("id")
            if row_id:
                ids.add(str(row_id))
    return ids


