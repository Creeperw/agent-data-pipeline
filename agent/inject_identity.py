async def call_teacher_executor(
    client: AsyncOpenAI,
    model_name: str,
    name: str,
    team: str,
    product: str,
    bucket_hint: str,
    max_retries: int,
) -> dict[str, Any] | None:
    system_prompt = EXECUTOR_TEACHER_SYSTEM_PROMPT_TEMPLATE.format(name=name, team=team, product=product)
    user_prompt = f"请围绕用户主题「{bucket_hint}」合成一条样本。"
    for attempt in range(max_retries):
        try:
            completion = await client.chat.completions.create(
                model=model_name,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.95,
                top_p=0.95,
            )
            return parse_json(completion.choices[0].message.content or "")
        except Exception as exc:
            if attempt < max_retries - 1:
                await asyncio.sleep(min(2**attempt, 30) + 1)
            else:
                print(f"\n[失败] executor 身份样本达到最大重试次数：{exc}")
                return None
    return None


async def call_teacher_planner(
    client: AsyncOpenAI,
    model_name: str,
    name: str,
    team: str,
    product: str,
    bucket_hint: str,
    max_retries: int,
    tool_scenario: str = "no_tools",
) -> dict[str, Any] | None:
    system_prompt = PLANNER_TEACHER_SYSTEM_PROMPT_TEMPLATE.format(
        name=name,
        team=team,
        product=product,
        tool_scenario=tool_scenario,
        tool_scenario_desc=PLANNER_TOOL_SCENARIO_DESC.get(tool_scenario, PLANNER_TOOL_SCENARIO_DESC["no_tools"]),
        tool_reasoning_hint=PLANNER_TOOL_REASONING_HINT.get(tool_scenario, PLANNER_TOOL_REASONING_HINT["no_tools"]),
    )
    user_prompt = f"请围绕用户主题「{bucket_hint}」合成一条规划阶段样本。"
    for attempt in range(max_retries):
        try:
            completion = await client.chat.completions.create(
                model=model_name,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.9,
                top_p=0.95,
            )
            return parse_json(completion.choices[0].message.content or "")
        except Exception as exc:
            if attempt < max_retries - 1:
                await asyncio.sleep(min(2**attempt, 30) + 1)
            else:
                print(f"\n[失败] planner 身份样本达到最大重试次数：{exc}")
                return None
    return None


