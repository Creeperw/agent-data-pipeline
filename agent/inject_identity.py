def render_executor_prompt(tokenizer, parsed: dict[str, Any]) -> str:
    assistant_content = f"<think>\n{parsed['reasoning'].strip()}\n</think>\n{parsed['answer'].strip()}"
    messages = [
        {"role": "system", "content": EXECUTOR_SYSTEM_PROMPT},
        {"role": "user", "content": parsed["user_query"].strip()},
        {"role": "assistant", "content": assistant_content},
    ]
    return tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=False)


def sample_planner_tools(rng: random.Random) -> tuple[str, list[dict[str, Any]]]:
    """为 planner 身份样本采样工具暴露方式。

    返回 (mode, tools)。mode 为 ``no_tools`` 表示工具列表为空；``random_subset``
    表示从全量工具目录中随机抽取若干个（对身份问题来说全部 irrelevant，模型仍
    应直接 planning_finish）。
    """

    modes, weights = zip(*PLANNER_TOOL_MODE_RATIO)
    mode = rng.choices(modes, weights=weights, k=1)[0]
    if mode == "no_tools" or not TOOL_CATALOG:
        return "no_tools", []
    pool = list(TOOL_CATALOG)
    rng.shuffle(pool)
    upper = min(PLANNER_TOOL_SUBSET_MAX, len(pool))
    lower = min(PLANNER_TOOL_SUBSET_MIN, upper)
    count = rng.randint(lower, upper) if upper >= lower else upper
    return "random_subset", pool[:count]


def render_planner_prompt(
    tokenizer,
    parsed: dict[str, Any],
    tools: list[dict[str, Any]],
) -> str:
    finish_reason = (
        PLANNER_FIXED_FINISH_REASON_NO_TOOLS if not tools else PLANNER_FIXED_FINISH_REASON_WITH_TOOLS
    )
    action_payload = {
        "intent": "其他",
        "action": "planning_finish",
        "finish_reason": finish_reason,
    }
    assistant_content = (
        f"<think>\n{parsed['reasoning'].strip()}\n</think>\n"
        + json.dumps(action_payload, ensure_ascii=False)
    )
    messages = [
        {"role": "system", "content": SFT_PLANNER_SYSTEM_PROMPT},
        {"role": "user", "content": parsed["user_query"].strip()},
        {"role": "assistant", "content": assistant_content},
    ]
    return tokenizer.apply_chat_template(messages, tools=tools, tokenize=False, add_generation_prompt=False)


def make_metadata(
    source_tag: str,
    planner: bool,
    tool_sampling_mode: str = "",
    tool_names: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "merge_source": "identity",
        "source": source_tag,
        "source_id": "",
        "step": 0,
        "action": "planning_finish",
        "include_reasoning": True,
        "planner_overridden": False,
        "tool_names": ",".join(tool_names or []),
        "has_tool_error": False,
        "has_file_write_plan": False,
        "file_written": False,
        "include_tool_errors": False,
        "answer_template_intent": "其他",
        "max_external_chars": 0,
        "planner_tool_sampling_mode": tool_sampling_mode if planner else "",
        "intent": "其他",
        "has_clarification_ask": False,
    }


