"""Synthesize identity SFT samples with the teacher LLM.

This script lives under ``agent/`` only because it imports config + tokenizer +
default health-domain prompts. It does **not** plug into the agent module pipeline; you run it
manually and it appends rows directly to the merged final-prompt JSONL.

Two stages are produced (configurable):

- **planner stage** (system = ``SFT_PLANNER_SYSTEM_PROMPT``):
  assistant outputs a strict JSON ``planning_finish`` with ``intent="其他"``.
  Only the ``<think>`` reasoning is generated by the LLM; the JSON action body
  is built deterministically so the model always learns "skip tools, finish
  planning when asked who/what I am".

- **executor stage** (system = ``EXECUTOR_SYSTEM_PROMPT``):
  the LLM generates BOTH the user question variant and the assistant answer
  (with ``<think>`` reasoning). Each call returns a JSON object so we can
  validate it before writing.

Both stages reuse ``agent.config.DistillConfig`` for the API key / base URL /
model / concurrency settings.

Examples::

    python -m agent.inject_identity --executor-total 200 --planner-total 200
    python -m agent.inject_identity --executor-total 100 --stage executor
    python -m agent.inject_identity --dry-run
"""

